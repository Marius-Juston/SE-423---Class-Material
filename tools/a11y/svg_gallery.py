#!/usr/bin/env -S uv run --script
# /// script
# requires-python = ">=3.12"
# dependencies = []
# [tool.uv]
# exclude-newer = "14 days"  # only releases at least two weeks old (supply-chain cooldown)
# ///
"""Give the published figure SVGs real names and descriptions, and fill the gallery.

    uv run tools/a11y/svg_gallery.py --root deploy_target [--index deploy_target/index.html]

For every SVG under <root>/Lectures/Figures/:
  - its description comes from (first found): reviewed alt text in
    Lectures/Slides/figures.toml (pictures whose source is this file), a `% alt: ...`
    comment in the TikZ source Lectures/Figures/<name>.tex (several lines are joined),
    or a <desc>/<title> the SVG already has;
  - <title> (the figure name) and <desc> are written into the SVG, which is marked
    role="img" and labelled by them, so the file is accessible when opened on its own;
  - an entry {title, alt, file} goes into the gallery between the
    /* INJECT_FIGURES_START */ and /* INJECT_FIGURES_END */ markers of --index.
Figures without any description keep their name as alt text and are listed at the end.
"""

import argparse
import html
import json
import re
import sys
import tomllib
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
MANIFEST = REPO / "Lectures/Slides/figures.toml"
TIKZ = REPO / "Lectures/Figures"
MARKERS = re.compile(r"/\* INJECT_FIGURES_START \*/.*?/\* INJECT_FIGURES_END \*/", re.S)


def nice_name(stem):
    return " ".join(w[:1].upper() + w[1:] for w in re.split(r"[_\-\s]+", stem) if w)


def reviewed_alt():
    """source path -> reviewed alt text, from the slide figure manifest."""
    if not MANIFEST.exists():
        return {}
    out = {}
    for f in tomllib.loads(MANIFEST.read_text()).get("figure", []):
        if f.get("alt") and f.get("alt_status", "reviewed") == "reviewed" and not f.get("decorative"):
            out.setdefault(f["source"], f["alt"])
    return out


def tikz_alt(stem):
    """Text of the `% alt:` comment(s) in Lectures/Figures/<stem>.tex, or None."""
    tex = TIKZ / f"{stem}.tex"
    if not tex.exists():
        return None
    lines, inside = [], False
    for line in tex.read_text().splitlines():
        m = re.match(r"\s*%\s*alt:\s*(.*)", line)
        if m:
            lines.append(m[1].strip())
            inside = True
        elif inside and re.match(r"\s*%\s+\S", line) and not re.match(r"\s*%\s*\w+:", line):
            lines.append(line.split("%", 1)[1].strip())  # continuation line
        else:
            inside = False
    return " ".join(lines) or None


# Tool boilerplate some generators put in <title>/<desc>; not a description.
GENERATED = re.compile(
    r"produced by|created with|generated by|gnuplot|matplotlib|inkscape|^figure ?\d*$|^untitled", re.I
)


def existing(svg_text, tag):
    m = re.search(rf"<{tag}\b[^>]*>(.*?)</{tag}>", svg_text, re.S)
    text = html.unescape(re.sub(r"<[^>]+>", "", m[1])).strip() if m else None
    return text if text and not GENERATED.search(text) else None


def annotate(svg_text, title, desc):
    """SVG with <title>/<desc> as the first children of the root, role="img" and
    aria-labelledby pointing at them (existing title/desc of the root are replaced)."""
    m = re.search(r"<svg\b[^>]*>", svg_text)
    if not m:
        return svg_text
    head = m[0]
    body = svg_text[m.end() :]
    body = re.sub(r"^\s*<title\b[^>]*>.*?</title>\s*", "", body, count=1, flags=re.S)
    body = re.sub(r"^\s*<desc\b[^>]*>.*?</desc>\s*", "", body, count=1, flags=re.S)
    for attr in ("role", "aria-labelledby"):
        head = re.sub(rf'\s{attr}="[^"]*"', "", head)
    head = head[:-1].rstrip("/") + ' role="img" aria-labelledby="fig-title fig-desc">'
    if m[0].endswith("/>"):
        return svg_text  # empty SVG; nothing to describe
    esc = html.escape
    meta = f'<title id="fig-title">{esc(title)}</title><desc id="fig-desc">{esc(desc)}</desc>'
    return svg_text[: m.start()] + head + meta + body


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--root", required=True, help="published site directory (e.g. deploy_target)")
    ap.add_argument("--index", help="page with the INJECT_FIGURES markers (default: <root>/index.html)")
    args = ap.parse_args()
    root = Path(args.root)
    index = Path(args.index) if args.index else root / "index.html"
    manifest = reviewed_alt()

    described, undescribed = [], []
    for svg in sorted((root / "Lectures/Figures").rglob("*.svg")):
        rel = svg.relative_to(root).as_posix()
        text = svg.read_text(errors="replace")
        title = nice_name(svg.stem)
        desc = manifest.get(rel) or tikz_alt(svg.stem) or existing(text, "desc") or existing(text, "title")
        if desc:
            svg.write_text(annotate(text, title, desc))
            described.append({"title": title, "alt": desc, "file": rel})
        else:
            undescribed.append({"title": title, "alt": title, "file": rel})
    entries = described + undescribed
    print(f"{len(described)} of {len(entries)} figures have a description", file=sys.stderr)

    if index.exists():
        payload = "".join(f"                {json.dumps(e, ensure_ascii=False)},\n" for e in entries)
        page = index.read_text()
        if not MARKERS.search(page):
            sys.exit(f"{index}: INJECT_FIGURES markers not found")
        page = MARKERS.sub(
            lambda _: f"/* INJECT_FIGURES_START */\n{payload}                /* INJECT_FIGURES_END */", page, count=1
        )
        index.write_text(page)


if __name__ == "__main__":
    main()
